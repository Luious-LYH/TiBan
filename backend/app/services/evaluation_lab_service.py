PROMPT_VERSION = "evaluation-lab-typed-answer-v1"
EVAL_SECRET_TTL_SECONDS = 2 * 60 * 60
_NON_LEARNER_BANK_IDS = {
    "bank-cmb-exam-real", "bank-general-science-foundations", "bank-arc-easy-local", "factory-generated-endoscopy-v1",
}


def _evaluation_secret_dir() -> Any:
    return config.RUNTIME_DATA_DIR / "evaluation-secrets"


def _evaluation_secret_path(run_id: str) -> Any:
    # run_id is generated by the service and never comes from a filesystem
    # path supplied by a user.
    return _evaluation_secret_dir() / f"{run_id}.json"


def _write_evaluation_secret(run_id: str, connection: dict[str, str]) -> None:
    directory = _evaluation_secret_dir()
    directory.mkdir(parents=True, exist_ok=True)
    now = time.time()
    for path in directory.glob("*.json"):
        try:
            if now - path.stat().st_mtime > EVAL_SECRET_TTL_SECONDS:
                path.unlink(missing_ok=True)
        except OSError:
            pass
    target = _evaluation_secret_path(run_id)
    temporary_path: str | None = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=directory, prefix=".eval-secret-", suffix=".tmp", delete=False) as handle:
            temporary_path = handle.name
            json.dump({**connection, "created_at": now}, handle, ensure_ascii=False, separators=(",", ":"))
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary_path, target)
        try:
            os.chmod(target, 0o600)
        except OSError:
            pass
    finally:
        if temporary_path:
            try:
                os.unlink(temporary_path)
            except OSError:
                pass


def _read_evaluation_secret(run_id: str) -> dict[str, str] | None:
    path = _evaluation_secret_path(run_id)
    try:
        if time.time() - path.stat().st_mtime > EVAL_SECRET_TTL_SECONDS:
            path.unlink(missing_ok=True)
            return None
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(payload, dict) or not payload.get("api_key"):
        return None
    return {key: str(payload[key]) for key in ("provider", "base_url", "api_key", "model") if payload.get(key)}


def _delete_evaluation_secret(run_id: str) -> None:
    try:
        _evaluation_secret_path(run_id).unlink(missing_ok=True)
    except OSError:
        pass


def _sha(value: object) -> str:
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()


def _p50(values: list[int]) -> int | None:
    return int(round(median(values))) if values else None


def _answer_letter(text: str) -> str | None:
    try:
        payload = json.loads(text.strip().strip("`"))
        if isinstance(payload, dict):
            value = str(payload.get("answer") or payload.get("option") or "").upper()
            found = re.search(r"\b([A-E])\b", value)
            if found:
                return found.group(1)
    except (TypeError, ValueError):
        pass
    found = re.search(r"(?:^|[^A-Z])([A-E])(?:[^A-Z]|$)", text.upper())
    return found.group(1) if found else None


def _prompt(question: QuestionModel, context: str = "") -> str:
    options = "\n".join(f"{chr(65 + index)}. {item.get('text', '')}" for index, item in enumerate(question.options))
    context_part = f"\nReference material (may be empty; use it only when relevant):\n{context}\n" if context else ""
    return (
        "Return JSON only, with exactly one field `answer` containing one option letter. "
        "Do not include reasoning or markdown.\n"
        f"Question: {question.stem}\nOptions:\n{options}{context_part}"
    )


def _expected_letter(question: QuestionModel) -> str | None:
    correct_id = str((question.grading_payload or {}).get("correct_option_id") or "")
    for index, option in enumerate(question.options or []):
        if str(option.get("id")) == correct_id:
            return chr(65 + index)
    return None


def _token_estimate(text: str) -> int:
    # The provider may not return usage. Keep this metric explicitly scoped to
    # retrieved context and deterministic; it is not presented as provider bill.
    return max(0, (len(text) + 3) // 4)


class EvaluationLabService:
    def catalog(self) -> dict[str, Any]:
        with SessionLocal() as session:
            rows = session.execute(
                select(QuestionBankModel, func.count(QuestionModel.question_id))
                .join(QuestionModel, QuestionModel.bank_id == QuestionBankModel.bank_id)
                .where(
                    QuestionBankModel.status == "published",
                    QuestionModel.business_usage == "user_ready",
                    QuestionModel.question_type == "single_choice",
                )
                .group_by(QuestionBankModel.bank_id)
                .order_by(QuestionBankModel.name)
            ).all()
            source_rows = session.execute(
                select(QuestionModel.bank_id, QuestionModel.source_type)
                .where(QuestionModel.bank_id.in_([bank.bank_id for bank, _ in rows]))
                .distinct()
            ).all() if rows else []
        source_types_by_bank: dict[str, set[str]] = {}
        for bank_id, source_type in source_rows:
            source_types_by_bank.setdefault(str(bank_id), set()).add(str(source_type))
        eligible_banks = []
        for bank, count in rows:
            if count <= 0 or bank.bank_id in _NON_LEARNER_BANK_IDS or bank.bank_id.startswith("adaptive-bank-"):
                continue
            if source_types_by_bank.get(bank.bank_id, set()) == {"test"}:
                continue
            eligible_banks.append({"bank_id": bank.bank_id, "domain_id": bank.domain_id, "name": bank.name, "version": bank.version, "eligible_question_count": int(count)})
        return {
            "banks": [
                item for item in eligible_banks
            ],
            "runtime_models": [LLM_MODEL] if LLM_MODEL else [],
            "default_profile": RetrievalProfile().public(),
            "prompt_version": PROMPT_VERSION,
        }

    def create_suite(self, *, bank_id: str, sample_size: int = 30, seed: int | None = None) -> dict[str, Any]:
        sample_size = max(1, min(100, int(sample_size)))
        seed = int(seed if seed is not None else random.SystemRandom().randint(1, 2_147_483_647))
        with SessionLocal() as session:
            bank = session.get(QuestionBankModel, bank_id)
            if bank is None or bank.status != "published" or bank.bank_id in _NON_LEARNER_BANK_IDS or bank.bank_id.startswith("adaptive-bank-"):
                raise KeyError("Question bank not found.")
            rows = list(session.scalars(select(QuestionModel).where(
                QuestionModel.bank_id == bank_id,
                QuestionModel.business_usage == "user_ready",
                QuestionModel.question_type == "single_choice",
            ).order_by(QuestionModel.question_id)))
            eligible = [row for row in rows if len(row.options or []) >= 2 and _expected_letter(row) is not None]
            if {row.source_type for row in eligible} == {"test"}:
                raise KeyError("Question bank not found.")
            if not eligible:
                raise ValueError("该题库没有可用于客观题评测的题目。")
            actual_size = min(sample_size, len(eligible))
            bank_hash = _sha({"bank_id": bank.bank_id, "version": bank.version, "questions": [row.question_id for row in eligible]})
            ids = [row.question_id for row in random.Random(seed).sample(eligible, actual_size)]
            suite_hash = _sha({"bank_id": bank.bank_id, "bank_hash": bank_hash, "question_ids": ids, "sample_size": actual_size, "seed": seed, "prompt_version": PROMPT_VERSION})
            suite = EvalSuiteModel(
                suite_id=f"suite_{uuid4().hex[:14]}", bank_id=bank.bank_id, domain_id=bank.domain_id,
                bank_version=bank.version, bank_hash=bank_hash, question_ids=ids, sample_size=actual_size,
                seed=seed, suite_hash=suite_hash, prompt_version=PROMPT_VERSION,
            )
            session.add(suite)
            session.commit()
            return self._suite_public(suite, bank.name)

    def latest_suite(self, *, bank_id: str) -> dict[str, Any] | None:
        with SessionLocal() as session:
            suite = session.scalar(
                select(EvalSuiteModel)
                .where(EvalSuiteModel.bank_id == bank_id)
                .order_by(EvalSuiteModel.created_at.desc(), EvalSuiteModel.suite_id.desc())
                .limit(1)
            )
            if suite is None:
                return None
            bank = session.get(QuestionBankModel, bank_id)
            return self._suite_public(suite, bank.name if bank else bank_id)

    def list_rag_profiles(self, *, bank_id: str) -> list[dict[str, Any]]:
        """Return reusable comparison profiles for one question bank.

        This is intentionally a small instance-level store.  It is not tied
        to a learner account and never contains provider credentials.
        """

        with SessionLocal() as session:
            rows = list(session.scalars(
                select(EvalRagProfileModel)
                .where(EvalRagProfileModel.bank_id == bank_id)
                .order_by(EvalRagProfileModel.created_at, EvalRagProfileModel.profile_id)
            ))
            return [self._rag_profile_public(row) for row in rows]

    def save_rag_profile(
        self,
        *,
        bank_id: str,
        profile: dict[str, Any],
        profile_id: str | None = None,
    ) -> dict[str, Any]:
        """Create or update one reusable RAG comparison profile.

        The same bounded ``RetrievalProfile`` parser used by evaluation runs
        is the single source of truth for persisted values.  Updating a saved
        row does not consume another profile slot; creating one is capped at
        two rows per bank.
        """

        normalized = RetrievalProfile.from_value(profile, fallback_mode="hybrid", fallback_limit=5).public()
        name = str(normalized.get("name") or "对比方案").strip()[:80]
        if not name:
            raise ValueError("方案名称不能为空。")
        with SessionLocal() as session:
            bank = session.get(QuestionBankModel, bank_id)
            if bank is None:
                raise KeyError("Question bank not found.")

            row: EvalRagProfileModel | None = None
            if profile_id:
                row = session.get(EvalRagProfileModel, profile_id)
                if row is None or row.bank_id != bank_id:
                    raise KeyError("RAG 对比方案不存在。")
            else:
                existing_count = session.scalar(
                    select(func.count(EvalRagProfileModel.profile_id))
                    .where(EvalRagProfileModel.bank_id == bank_id)
                ) or 0
                if int(existing_count) >= 2:
                    raise ValueError("每个题库最多保存两个对比方案。")
                row = EvalRagProfileModel(
                    profile_id=f"ragprofile_{uuid4().hex[:14]}",
                    bank_id=bank_id,
                    created_at=datetime.utcnow(),
                )
                session.add(row)

            row.name = name
            row.mode = str(normalized["mode"])
            row.top_k = int(normalized["top_k"])
            row.candidate_pool = int(normalized["candidate_pool"])
            row.rerank_enabled = bool(normalized["rerank_enabled"])
            row.rrf_k = int(normalized["rrf_k"])
            row.section_dedupe = bool(normalized["section_dedupe"])
            row.updated_at = datetime.utcnow()
            session.commit()
            session.refresh(row)
            return self._rag_profile_public(row)

    def delete_rag_profile(self, *, bank_id: str, profile_id: str) -> None:
        with SessionLocal() as session:
            row = session.get(EvalRagProfileModel, profile_id)
            if row is None or row.bank_id != bank_id:
                raise KeyError("RAG 对比方案不存在。")
            session.delete(row)
            session.commit()

    def create_model_experiment(
        self,
        *,
        suite_id: str,
        models: list[str],
        base_url: str | None = None,
        api_key: str | None = None,
        provider: str | None = None,
    ) -> dict[str, Any]:
        candidates = list(dict.fromkeys(item.strip()[:180] for item in models if item and item.strip()))
        if not candidates:
            candidates = [LLM_MODEL]
        connection = self._resolve_connection(
            model=candidates[0], base_url=base_url, api_key=api_key, provider=provider,
        )
        return self._create_experiment(suite_id=suite_id, experiment_type="model", models=candidates, variants=[], connection=connection)

    def create_rag_experiment(self, *, suite_id: str, variants: list[dict[str, Any]], model: str | None = None) -> dict[str, Any]:
        if len(variants) > 2:
            raise ValueError("RAG 评测最多支持两个对比方案。")
        cleaned = [RetrievalProfile.from_value(value, fallback_mode="hybrid", fallback_limit=5).public() for value in variants]
        answer_model = (model or LLM_MODEL).strip()
        connection = self._resolve_connection(model=answer_model)
        return self._create_experiment(suite_id=suite_id, experiment_type="rag", models=[answer_model], variants=cleaned, connection=connection)

    def _resolve_connection(
        self,
        *,
        model: str,
        base_url: str | None = None,
        api_key: str | None = None,
        provider: str | None = None,
    ) -> dict[str, str] | None:
        supplied_base = (base_url or "").strip()
        supplied_key = (api_key or "").strip()
        if bool(supplied_base) != bool(supplied_key):
            raise ValueError("自定义 API 需要同时填写 Base URL 和 API Key。")
        if supplied_base and supplied_key:
            preflight = llm_provider.preflight(supplied_base)
            if not preflight.get("ok"):
                raise ValueError("自定义 API 地址不符合当前实例的安全策略。")
            return {
                "provider": (provider or "byok_openai_compatible").strip()[:120],
                "base_url": llm_provider._normalize_base_url(supplied_base),
                "api_key": supplied_key,
                "model": model,
            }
        return llm_provider.runtime_request_config(model=model)

    def _create_experiment(
        self,
        *,
        suite_id: str,
        experiment_type: str,
        models: list[str],
        variants: list[dict[str, Any]],
        connection: dict[str, str] | None,
    ) -> dict[str, Any]:
        with SessionLocal() as session:
            suite = session.get(EvalSuiteModel, suite_id)
            if suite is None:
                raise KeyError("评测集不存在。")
            safe_connection = {key: value for key, value in (connection or {}).items() if key != "api_key"}
            snapshot = self._runtime_snapshot(session, suite, answer_model=models[0]) if experiment_type == "rag" else {
                "prompt_version": suite.prompt_version, "temperature": 0, "allow_fallback": False,
                "provider": safe_connection.get("provider", LLM_PROVIDER),
                "base_url": safe_connection.get("base_url", ""), "model_candidates": models,
            }
            experiment = EvalExperimentModel(
                experiment_id=f"evalexp_{uuid4().hex[:14]}", experiment_type=experiment_type,
                suite_id=suite_id, status="queued", fixed_snapshot=snapshot,
            )
            session.add(experiment)
            run_specs: list[tuple[str, str, dict[str, Any] | None]] = []
            if experiment_type == "model":
                run_specs = [(candidate, candidate, None) for candidate in models]
            else:
                baseline = RetrievalProfile().public()
                run_specs = [("TiBan Default", models[0], baseline)] + [
                    (str(profile["name"]), models[0], profile) for profile in variants
                ]
            runs: list[EvalLabRunModel] = []
            for name, model, profile in run_specs:
                run_id, job_id = f"evalrun_{uuid4().hex[:14]}", f"evaluation_{uuid4().hex[:12]}"
                job = BackgroundJobModel(
                    job_id=job_id, job_type=f"evaluation_{experiment_type}", target_id=run_id,
                    status="queued", stage="queued", progress=0,
                    idempotency_key=f"evaluation:{run_id}", detail={"experiment_id": experiment.experiment_id, "run_id": run_id},
                )
                run = EvalLabRunModel(
                    run_id=run_id, experiment_id=experiment.experiment_id, job_id=job_id, name=name,
                    provider=(connection or {}).get("provider", LLM_PROVIDER),
                    provider_base_url=(connection or {}).get("base_url", ""),
                    model=model, retrieval_profile=profile, status="queued",
                )
                session.add_all([job, run])
                runs.append(run)
            session.commit()
            experiment_id = experiment.experiment_id
        for run in runs:
            if connection and connection.get("api_key"):
                _write_evaluation_secret(run.run_id, {**connection, "model": run.model})
            self._dispatch(run.run_id)
        return self.experiment(experiment_id)

    def _dispatch(self, run_id: str) -> None:
        try:
            from app.workers.background_worker import process_evaluation_lab_actor
            process_evaluation_lab_actor.send(run_id)
        except Exception as exc:
            self._fail_dispatch(run_id, type(exc).__name__)

    def _fail_dispatch(self, run_id: str, error: str) -> None:
        with SessionLocal() as session:
            run = session.get(EvalLabRunModel, run_id)
            if run is None:
                return
            job = session.get(BackgroundJobModel, run.job_id)
            run.status = "failed"
            if job:
                job.status, job.stage, job.error_message, job.completed_at = "failed", "dispatch_failed", error, datetime.utcnow()
            session.commit()
            self._sync_experiment_status(session, run.experiment_id)

    def process_run(self, run_id: str) -> dict[str, Any]:
        with SessionLocal() as session:
            run = session.get(EvalLabRunModel, run_id)
            if run is None:
                # A confirmed re-sample can remove a run while its worker is
                # still queued. This is an intentional cancellation, not a
                # transient failure that should be retried by Dramatiq.
                return {"run_id": run_id, "status": "cancelled"}
            if run.status == "completed":
                return {"run_id": run_id, "status": "completed"}
            experiment = session.get(EvalExperimentModel, run.experiment_id)
            suite = session.get(EvalSuiteModel, experiment.suite_id) if experiment else None
            job = session.get(BackgroundJobModel, run.job_id)
            if experiment is None or suite is None or job is None:
                return {"run_id": run_id, "status": "cancelled"}
            questions = {row.question_id: row for row in session.scalars(select(QuestionModel).where(QuestionModel.question_id.in_(suite.question_ids)))}
            ordered = [questions[item] for item in suite.question_ids if item in questions]
            snapshot = dict(experiment.fixed_snapshot or {})
            run.status, job.status, job.stage, job.progress = "running", "running", "running", 2
            experiment.status = "running"
            job.started_at = datetime.utcnow()
            session.commit()
        results: list[dict[str, Any]] = []
        try:
            if experiment.experiment_type == "rag":
                self._assert_rag_snapshot_is_current(snapshot)
            for index, question in enumerate(ordered, start=1):
                results.append(self._evaluate_case(question, run, snapshot=snapshot))
                if not self._record_case_progress(run_id, results[-1], index, len(ordered)):
                    return {"run_id": run_id, "status": "cancelled"}
            aggregate = self._aggregate(results, experiment.experiment_type)
            with SessionLocal() as session:
                current = session.get(EvalLabRunModel, run_id)
                current_job = session.get(BackgroundJobModel, current.job_id) if current else None
                if current is None or current_job is None:
                    return {"run_id": run_id, "status": "cancelled"}
                current.status, current.aggregate, current.completed_at = "completed", aggregate, datetime.utcnow()
                current_job.status, current_job.stage, current_job.progress, current_job.completed_at = "completed", "completed", 100, datetime.utcnow()
                session.commit()
                self._sync_experiment_status(session, current.experiment_id)
            return {"run_id": run_id, "status": "completed"}
        except Exception as exc:
            with SessionLocal() as session:
                current = session.get(EvalLabRunModel, run_id)
                if current is None:
                    # The result was removed by an explicit user-confirmed
                    # resample while the provider call was in flight.
                    return {"run_id": run_id, "status": "cancelled"}
                job = session.get(BackgroundJobModel, current.job_id)
                current.status = "failed"
                if job:
                    job.status, job.stage, job.error_message, job.completed_at = "failed", "failed", type(exc).__name__, datetime.utcnow()
                session.commit()
                self._sync_experiment_status(session, current.experiment_id)
            raise
        finally:
            _delete_evaluation_secret(run_id)

    def _evaluate_case(self, question: QuestionModel, run: EvalLabRunModel, *, snapshot: dict[str, Any]) -> dict[str, Any]:
        profile = RetrievalProfile.from_value(run.retrieval_profile, fallback_mode="hybrid", fallback_limit=5) if run.retrieval_profile else None
        # The shared RagService receives the exact version set that was
        # present at experiment creation; a later upload cannot contaminate a
        # queued run while its persisted snapshot claims otherwise.
        frozen_versions = [str(item["version_id"]) for item in snapshot.get("knowledge_versions", []) if isinstance(item, dict) and item.get("version_id")]
        citations = (
            rag_service.retrieve(question.stem, profile=profile, domain_id=question.domain_id, version_ids=frozen_versions)
            if profile and frozen_versions
            else []
        )
        context = "\n\n".join(f"[{item.document_name} / {item.section}] {item.snippet}" for item in citations)
        call_options: dict[str, Any] = {}
        runtime_secret = _read_evaluation_secret(run.run_id)
        if runtime_secret:
            call_options.update(
                base_url=runtime_secret.get("base_url"),
                api_key=runtime_secret.get("api_key"),
                provider=runtime_secret.get("provider"),
            )
        result = llm_provider.chat(
            system_prompt="You are an evaluation respondent. Follow the typed answer contract. This is learning evaluation, not professional advice.",
            user_prompt=_prompt(question, context), model=run.model, temperature=0, max_tokens=80, allow_fallback=False, **call_options,
        )
        expected, answer = _expected_letter(question), _answer_letter(result.text) if result.ok else None
        valid = bool(result.ok and answer and expected and answer in {chr(65 + i) for i in range(len(question.options))})
        gold = (question.grading_payload or {}).get("gold_chunk_ids") or (question.grading_payload or {}).get("gold_evidence_chunk_ids") or []
        return {
            "question_id": question.question_id, "valid_response": valid, "provider_success": bool(result.ok),
            "correct": bool(valid and answer == expected) if result.ok else None,
            "latency_ms": result.latency_ms, "total_tokens": int((result.usage or {}).get("total_tokens") or 0),
            "context_tokens": _token_estimate(context), "retrieved_chunk_ids": [item.chunk_id for item in citations],
            "gold_chunk_ids": [str(item) for item in gold] if isinstance(gold, list) else [],
        }

    def _record_case_progress(self, run_id: str, result: dict[str, Any], index: int, total: int) -> bool:
        with SessionLocal() as session:
            run = session.get(EvalLabRunModel, run_id)
            if run is None:
                return False
            job = session.get(BackgroundJobModel, run.job_id)
            if job is None:
                return False
            session.add(EvalLabCaseModel(case_id=f"evcase_{uuid4().hex[:14]}", run_id=run_id, **result))
            job.stage, job.progress = "evaluating", min(99, 5 + int(index / max(1, total) * 90))
            session.commit()
            return True

    def _aggregate(self, results: list[dict[str, Any]], experiment_type: str) -> dict[str, Any]:
        count = len(results)
        provider = sum(bool(item["provider_success"]) for item in results)
        valid = sum(bool(item["valid_response"]) for item in results)
        correct = sum(bool(item["correct"]) for item in results)
        latencies = [int(item["latency_ms"]) for item in results if item["latency_ms"] is not None]
        payload: dict[str, Any] = {
            "sample_count": count, "accuracy": round(correct / count, 4) if count else 0.0,
            "valid_response_rate": round(valid / count, 4) if count else 0.0,
            "provider_success_rate": round(provider / count, 4) if count else 0.0,
            "p50_latency_ms": _p50(latencies),
            "avg_tokens_per_question": round(sum(int(item["total_tokens"]) for item in results) / count, 2) if count else 0.0,
        }
        if experiment_type == "rag":
            gold_cases = [item for item in results if item["gold_chunk_ids"]]
            payload.update({
                "answer_accuracy": payload["accuracy"],
                "avg_context_tokens": round(sum(int(item["context_tokens"]) for item in results) / count, 2) if count else 0.0,
                "recall_at_k": round(sum(bool(set(item["gold_chunk_ids"]) & set(item["retrieved_chunk_ids"])) for item in gold_cases) / len(gold_cases), 4) if gold_cases else None,
            })
        return payload

    def _runtime_snapshot(self, session: Any, suite: EvalSuiteModel, *, answer_model: str) -> dict[str, Any]:
        state = session.get(VectorIndexStateModel, "knowledge")
        version_rows = session.execute(
            select(DocumentVersionModel, SourceDocumentModel)
            .join(SourceDocumentModel, SourceDocumentModel.document_id == DocumentVersionModel.document_id)
            .join(KnowledgeChunkModel, KnowledgeChunkModel.version_id == DocumentVersionModel.version_id)
            .where(
                SourceDocumentModel.business_usage == "knowledge_base",
                SourceDocumentModel.enabled.is_(True),
                SourceDocumentModel.ai_ingestion_allowed.is_(True),
                SourceDocumentModel.status.not_in(["queued", "rebuilding", "indexing", "uploaded", "failed", "disabled", "retired"]),
            )
        ).all()
        latest_versions: dict[str, tuple[datetime, str, str]] = {}
        for version, document in version_rows:
            candidate = (version.created_at, version.version_id, version.content_hash)
            current = latest_versions.get(document.document_id)
            if current is None or candidate[:2] > current[:2]:
                latest_versions[document.document_id] = candidate
        knowledge_versions = [
            {"document_id": document_id, "version_id": version_id, "content_hash": content_hash}
            for document_id, (_, version_id, content_hash) in sorted(latest_versions.items())
        ]
        return {
            "suite_hash": suite.suite_hash, "knowledge_snapshot": _sha(knowledge_versions), "knowledge_document_count": len(knowledge_versions),
            "knowledge_versions": knowledge_versions,
            "embedding_provider": state.provider if state else None, "embedding_model": state.model_id if state else None,
            "index_version": state.index_version if state else None, "prompt_version": suite.prompt_version,
            # Use the selected candidate, rather than the mutable instance
            # default, so the persisted run conditions accurately describe
            # what the worker will send to the provider.
            "answer_model": answer_model, "temperature": 0, "allow_fallback": False,
        }

    @staticmethod
    def _assert_rag_snapshot_is_current(snapshot: dict[str, Any]) -> None:
        """Do not silently compare profiles against an altered vector runtime."""
        current = rag_service.index_state()
        for snapshot_key, runtime_key in (("embedding_provider", "provider"), ("embedding_model", "model"), ("index_version", "index_version")):
            expected = snapshot.get(snapshot_key)
            if expected is not None and current.get(runtime_key) != expected:
                raise RuntimeError("RAG index changed after this experiment was frozen; create a new experiment.")

    def experiment(self, experiment_id: str) -> dict[str, Any]:
        with SessionLocal() as session:
            experiment = session.get(EvalExperimentModel, experiment_id)
            if experiment is None:
                raise KeyError("Evaluation experiment not found.")
            return self._experiment_public(session, experiment)

    def latest_experiment(self, *, bank_id: str, experiment_type: str) -> dict[str, Any] | None:
        """Read the most recent durable experiment for one bank and lab tab."""
        with SessionLocal() as session:
            experiment = session.scalar(
                select(EvalExperimentModel)
                .join(EvalSuiteModel, EvalSuiteModel.suite_id == EvalExperimentModel.suite_id)
                .where(
                    EvalSuiteModel.bank_id == bank_id,
                    EvalExperimentModel.experiment_type == experiment_type,
                )
                .order_by(EvalExperimentModel.created_at.desc(), EvalExperimentModel.experiment_id.desc())
                .limit(1)
            )
            return self._experiment_public(session, experiment) if experiment else None

    def delete_experiments(self, *, bank_id: str, experiment_type: str) -> dict[str, int]:
        """Delete results for one bank/tab while retaining immutable suites."""
        with SessionLocal() as session:
            experiments = list(session.scalars(
                select(EvalExperimentModel)
                .join(EvalSuiteModel, EvalSuiteModel.suite_id == EvalExperimentModel.suite_id)
                .where(
                    EvalSuiteModel.bank_id == bank_id,
                    EvalExperimentModel.experiment_type == experiment_type,
                )
            ))
            if not experiments:
                return {"deleted_experiment_count": 0, "deleted_run_count": 0}

            experiment_ids = [item.experiment_id for item in experiments]
            runs = list(session.scalars(
                select(EvalLabRunModel).where(EvalLabRunModel.experiment_id.in_(experiment_ids))
            ))
            run_ids = [item.run_id for item in runs]
            job_ids = [item.job_id for item in runs]
            if run_ids:
                session.execute(delete(EvalLabCaseModel).where(EvalLabCaseModel.run_id.in_(run_ids)))
                session.execute(delete(EvalLabRunModel).where(EvalLabRunModel.run_id.in_(run_ids)))
            if job_ids:
                session.execute(delete(BackgroundJobModel).where(BackgroundJobModel.job_id.in_(job_ids)))
            session.execute(delete(EvalExperimentModel).where(EvalExperimentModel.experiment_id.in_(experiment_ids)))
            session.commit()

        for run_id in run_ids:
            _delete_evaluation_secret(run_id)
        return {
            "deleted_experiment_count": len(experiments),
            "deleted_run_count": len(runs),
        }

    def _experiment_public(self, session: Any, experiment: EvalExperimentModel) -> dict[str, Any]:
        suite = session.get(EvalSuiteModel, experiment.suite_id)
        if suite is None:
            raise KeyError("Evaluation suite not found.")
        bank = session.get(QuestionBankModel, suite.bank_id)
        runs = list(session.scalars(
            select(EvalLabRunModel)
            .where(EvalLabRunModel.experiment_id == experiment.experiment_id)
            .order_by(EvalLabRunModel.created_at)
        ))
        jobs = {
            job.job_id: job for job in session.scalars(
                select(BackgroundJobModel).where(
                    BackgroundJobModel.job_id.in_([run.job_id for run in runs])
                )
            )
        }
        return {
            "experiment_id": experiment.experiment_id,
            "experiment_type": experiment.experiment_type,
            "status": experiment.status,
            "suite": self._suite_public(suite, bank.name if bank else suite.bank_id),
            "fixed_snapshot": experiment.fixed_snapshot,
            "runs": [self._run_public(run, jobs.get(run.job_id)) for run in runs],
            "created_at": experiment.created_at.isoformat(),
        }

