    def _sync_experiment_status(self, session: Any, experiment_id: str) -> None:
        experiment = session.get(EvalExperimentModel, experiment_id)
        if experiment is None:
            return
        statuses = list(session.scalars(select(EvalLabRunModel.status).where(EvalLabRunModel.experiment_id == experiment_id)))
        if statuses and all(status == "completed" for status in statuses):
            experiment.status, experiment.completed_at = "completed", datetime.utcnow()
        elif any(status == "running" for status in statuses):
            experiment.status = "running"
        elif statuses and all(status in {"completed", "failed"} for status in statuses):
            experiment.status, experiment.completed_at = "partial_failed", datetime.utcnow()
        session.commit()


